  if (doFix) {
    let files = 0, chars = 0;
    for (const f of walk(root)) {
      const src = readFileSync(f, 'utf8');
      const { out, changed } = fixText(src);
      if (changed) { writeFileSync(f, out); files++; chars += changed; }
    }
    console.log(`改了 ${chars} 個字,${files} 個檔`);
  }
  const hits = scanAll(root);
  const byFile = new Map<string, number>();
